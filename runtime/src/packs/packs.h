// Player-supplied pack build snapshot. No runtime PPC code patching or JIT.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace packs {
struct Field {
  std::string name;
  std::vector<double> values;
};
struct TextureRule {
  std::vector<Field> fields;
};
enum class ShaderStage { vertex, geometry, pixel };
struct ShaderReplacement {
  uint64_t base_hash = 0;
  uint64_t auxiliary_hash = 0;
  ShaderStage stage = ShaderStage::pixel;
  std::string source; // Cemu GLSL with preset substitutions; W2 compiles it.
};
struct Pack {
  std::string name;
  std::vector<TextureRule> textures;
  std::vector<ShaderReplacement> shaders;
  std::vector<Field> control;
};
struct MemoryWrite {
  uint32_t address = 0;
  std::vector<uint8_t> bytes;
};
struct BuildPlan {
  std::string rpx_sha256;
  std::string fingerprint;
  uint32_t module_checksum = 0;
  std::vector<MemoryWrite> initial_memory;
  std::vector<Pack> packs;
};
// Defined by packs_generated.inc when generated by tools/packs/recompile.py.
// An empty plan is returned for the existing build without packs.
const BuildPlan &compiled_plan();

// Hash the exact source snapshot handed to the RPX loader.
std::string sha256(const uint8_t *bytes, size_t size);
bool validate_renderer_fields(const BuildPlan &plan, bool textures,
                              bool shaders, std::string &error);
bool has_timing_pack(const BuildPlan &plan);

struct TextureDescription {
  uint32_t width = 0, height = 0, depth = 0;
  uint32_t format = 0, tile_mode = 0;
  bool in_mem1 = false;
};
// Match against the ORIGINAL guest texture, before any overwrite. Later rules
// override earlier fields, preserving the enabled-pack order from the manifest.
// Effective identity dimensions are removed after merging (dimensions
// truncate).
bool matches(const TextureRule &rule, const TextureDescription &texture);
std::vector<Field> texture_overrides(const BuildPlan &plan,
                                     const TextureDescription &texture);
const ShaderReplacement *find_shader(const BuildPlan &plan, uint64_t base_hash,
                                     uint64_t auxiliary_hash,
                                     ShaderStage stage);

// Renderer implementors must reject unsupported fields/capabilities in prepare,
// before changing GPU state. Commit is called only after ALL packs are
// accepted. Nonidentity pack dimensions replace built-in scaling only for the
// matching texture; unmatched and identity-only textures retain built-in
// scaling.
class RendererHooks {
public:
  virtual ~RendererHooks() = default;
  virtual bool prepare(const BuildPlan &plan, std::string &error) = 0;
  virtual void commit(const BuildPlan &plan) = 0;
};

// Loader/host calls this AFTER RPX relocation and BEFORE starting any guest
// thread. validate_range must verify that every write is backed by writable
// guest memory (including the appended codecave). All ranges are checked before
// any writes. sha256 must be computed from the RPX actually loaded, never from
// the plan.
struct GuestMemory {
  void *context = nullptr;
  bool (*validate_range)(void *, uint32_t, size_t) = nullptr;
  void (*write)(void *, uint32_t, const uint8_t *, size_t) = nullptr;
};
bool install(const BuildPlan &plan, const std::string &rpx_sha256,
             const GuestMemory &memory, RendererHooks &renderer,
             std::string &error);
} // namespace packs
